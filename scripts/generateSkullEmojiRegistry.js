/**
 * One-shot generator: scans assets/skull_*.png → src/constants/skullEmojiRegistry.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const assetsDir = path.join(root, 'assets');
const outFile = path.join(root, 'src', 'constants', 'skullEmojiRegistry.js');

const all = fs
  .readdirSync(assetsDir)
  .filter((f) => /^skull_.*\.png$/i.test(f))
  .map((f) => f.replace(/\.png$/i, ''))
  .sort();

const entries = all.map((k) => `  ${k}: require('../../assets/${k}.png'),`).join('\n');

const content = `/**
 * BAWAAL skull emoji registry — every assets/skull_*.png → local require().
 * Source of truth for SKULL_EMOJIS / SKULL_EMOJI_KEYS / Vault / shortcodes.
 * Do not invent keys; filenames are the keys (e.g. skull_hattrick).
 * Regenerated by scripts/generateSkullEmojiRegistry.js
 */
/* eslint-disable global-require */

/** @type {Readonly<Record<string, number>>} */
export const SKULL_EMOJIS = Object.freeze({
${entries}
});

/** Ordered vault keys — all registered skull_* assets. */
export const SKULL_EMOJI_KEYS = Object.freeze(Object.keys(SKULL_EMOJIS));

/** Default fallback when a skull key is missing. */
export const DEFAULT_SKULL_EMOJI_KEY = 'skull_laugh';

function normalizeSkullKey(name) {
  if (name == null) return '';
  return String(name)
    .trim()
    .toLowerCase()
    .replace(/^:+|:+$/g, '')
    .replace(/\\.png$/i, '')
    .replace(/[\\s-]+/g, '_');
}

/**
 * Resolve a skull key / shortcode / filename to a bundled Image source.
 * Missing keys fall back to skull_laugh so callers never crash.
 */
export function getSkullEmojiSource(name) {
  const key = normalizeSkullKey(name);
  const withPrefix = key.startsWith('skull_') ? key : key ? \`skull_\${key}\` : '';
  return (
    SKULL_EMOJIS[key] ||
    SKULL_EMOJIS[withPrefix] ||
    SKULL_EMOJIS[DEFAULT_SKULL_EMOJI_KEY]
  );
}

export function hasSkullEmoji(name) {
  const key = normalizeSkullKey(name);
  if (!key) return false;
  if (SKULL_EMOJIS[key]) return true;
  const withPrefix = key.startsWith('skull_') ? key : \`skull_\${key}\`;
  return Boolean(SKULL_EMOJIS[withPrefix]);
}

/** Sports / match-day quick tray (horizontal Banter + Arena reactions). */
export const SKULL_QUICK_REACTION_KEYS = Object.freeze([
  'skull_goal',
  'skull_hattrick',
  'skull_mvp',
  'skull_red_card',
  'skull_yellow_card_no_text',
  'skull_var_check',
  'skull_away_day',
  'skull_clutch',
  'skull_hyped',
  'skull_facepalm',
  'skull_heartbreak',
  'skull_champion',
]);
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content);
console.log(`Wrote ${outFile} with ${all.length} skull keys`);
