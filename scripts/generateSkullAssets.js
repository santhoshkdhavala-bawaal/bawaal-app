/**
 * Scans assets/skull_*.png → src/utils/skullAssets.js (SKULL_ASSETS dictionary).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const assetsDir = path.join(root, 'assets');
const outFile = path.join(root, 'src', 'utils', 'skullAssets.js');

const all = fs
  .readdirSync(assetsDir)
  .filter((f) => /^skull_.*\.png$/i.test(f))
  .map((f) => f.replace(/\.png$/i, ''))
  .sort();

const entries = all
  .map((k) => `  ${k}: require('../../assets/${k}.png'),`)
  .join('\n');

const content = `/**
 * BAWAAL local skull image map — every assets/skull_*.png → require().
 * Reusable SKULL_ASSETS dictionary for War Cry votes, trays, and UI chrome.
 * Keys match filenames without .png (e.g. skull_fire_full, skull_bluefire).
 * Regenerated by scripts/generateSkullAssets.js
 */
/* eslint-disable global-require */

/** @type {Readonly<Record<string, number>>} */
export const SKULL_ASSETS = Object.freeze({
${entries}
});

/** Ordered keys for every registered skull asset. */
export const SKULL_ASSET_KEYS = Object.freeze(Object.keys(SKULL_ASSETS));

/** War Cry Vote A — Red Fire Skull. */
export const VOTE_SKULL_A = SKULL_ASSETS.skull_fire_full;

/** War Cry Vote B — Blue Ice Skull. */
export const VOTE_SKULL_B = SKULL_ASSETS.skull_bluefire;

function normalizeSkullAssetKey(name) {
  if (name == null) return '';
  return String(name)
    .trim()
    .toLowerCase()
    .replace(/^:+|:+$/g, '')
    .replace(/\\.png$/i, '')
    .replace(/[\\s-]+/g, '_');
}

/**
 * Resolve a skull key / shortcode / filename to a bundled Image source.
 * @param {string|null|undefined} name
 * @returns {number|undefined}
 */
export function getSkullAsset(name) {
  const key = normalizeSkullAssetKey(name);
  if (!key) return undefined;
  if (SKULL_ASSETS[key]) return SKULL_ASSETS[key];
  const withPrefix = key.startsWith('skull_') ? key : \`skull_\${key}\`;
  return SKULL_ASSETS[withPrefix];
}

export function hasSkullAsset(name) {
  return Boolean(getSkullAsset(name));
}
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, content);
console.log(
  `wrote ${path.relative(root, outFile)} (${all.length} keys); fire_full=${all.includes('skull_fire_full')} bluefire=${all.includes('skull_bluefire')}`
);
